/**
 * 이 기기가 보는 오늘 날짜.
 *
 * `new Date().toISOString()` 은 UTC 날짜를 준다. 한국은 UTC+9 라서 자정부터 아침
 * 9시까지는 어제 날짜가 나온다. 선생님이 1교시 전에 시간표를 확인하는 시간대가
 * 정확히 거기다. 그 시간에 열면 오늘 탭에 어제 시간표가 뜨고, 일과 담당 관제판의
 * 오늘 건수도 어제 것이 된다.
 *
 * 화면마다 오늘을 따로 구하고 있었다. 교사 화면은 지역 날짜를, 일과 담당 화면과
 * 학급 공개 화면은 UTC 날짜를 썼다. 그래서 아침 9시 전에는 두 화면이 서로 다른
 * 날을 오늘이라고 불렀다. 한 군데서만 정한다.
 *
 * 감사 기록의 시각은 이것을 쓰지 않는다. 그쪽은 언제 일어났는지를 남기는 것이라
 * UTC 로 적는 편이 맞다. 여기서 정하는 것은 달력의 하루다.
 */
export function localDate(at: Date = new Date()): string {
  return [
    at.getFullYear(),
    String(at.getMonth() + 1).padStart(2, '0'),
    String(at.getDate()).padStart(2, '0'),
  ].join('-');
}
